#!/usr/bin/env python3
"""Extracts a compact envelope from a sea recording so the synth can follow a real pattern.

  scripts/analyze-sea-envelope.py <recording> [start_s] [length_s] > src/components/sections/Hero/scenes/seaEnvelope.ts

Per 50 ms hop: RMS level and spectral centroid (brightness), both normalized to 0..255 and
base64-encoded. ~1200 hops for 60 s ≈ 3 KB, versus ~260 KB for the Opus clip.
Needs ffmpeg and numpy.
"""
import base64
import subprocess
import sys

import numpy as np

src = sys.argv[1]
start = float(sys.argv[2]) if len(sys.argv) > 2 else 47.8
length = float(sys.argv[3]) if len(sys.argv) > 3 else 60.0
rate = 16000
hop_s = 0.05

pcm = subprocess.run(
    ["ffmpeg", "-v", "error", "-ss", str(start), "-t", str(length), "-i", src,
     "-af", "highpass=f=150", "-ac", "1", "-ar", str(rate), "-f", "f32le", "-"],
    check=True, capture_output=True,
).stdout
x = np.frombuffer(pcm, dtype=np.float32)
hop = int(rate * hop_s)
frames = len(x) // hop
x = x[: frames * hop].reshape(frames, hop)

rms = np.sqrt((x ** 2).mean(axis=1))
window = np.hanning(hop)
spec = np.abs(np.fft.rfft(x * window, axis=1))
freqs = np.fft.rfftfreq(hop, 1 / rate)
centroid = (spec * freqs).sum(axis=1) / np.maximum(spec.sum(axis=1), 1e-9)

# Smooth a touch (the synth ramps between hops anyway) and normalize.
kernel = np.ones(3) / 3
rms = np.convolve(rms, kernel, mode="same")
centroid = np.convolve(centroid, kernel, mode="same")
level = np.clip(rms / np.percentile(rms, 99), 0, 1)
bright = np.clip((centroid - 300) / 2200, 0, 1)  # 300 Hz → 0, 2500 Hz → 1

def b64(a: np.ndarray) -> str:
    return base64.b64encode(np.round(a * 255).astype(np.uint8).tobytes()).decode()

print("// Generated by scripts/analyze-sea-envelope.py — do not edit by hand.")
print(f"// Source: {src.split('/')[-1]} from {start}s, {length}s, hop {hop_s}s.")
print("export const seaEnvelope = {")
print(f"  hop: {hop_s},")
print(f"  level: '{b64(level)}',")
print(f"  bright: '{b64(bright)}',")
print("};")
